#!/usr/bin/env python3
"""Generate the per-model MI355X shard manifests.

    python scripts/gen_mi355x_manifests.py

One YAML per model under experiments/mi355x/ — sharding across cluster nodes is
"give each node its model's file", never editing experiment definitions to fit
the cluster. Every model gets the same variant pattern:

  base            the tuned config
  rccl-log        RCCL_DEBUG=INFO (one per model: which algo/proto RCCL picked)
  bad-tiny-batch  batching starved            } deliberately bad rows — controlled
  bad-no-graphs   --enforce-eager launch gaps } variation for attribution to
  bad-kv-squeeze  KV cache squeezed           } work against
  powercap        SAME config as base; run only after `amd-smi set --power-cap`
                  on the host (tokens/watt measured, not inferred)

Kimi K2.5 additionally gets:

  rccl-inspector  per-communicator detail (one config, not the whole matrix)
  roctx-check     vLLM layerwise tracing flag, to answer once whether it emits
                  ROCTx on ROCm; if the rocprof marker CSV stays empty, drop it

The Qwen3.6 row is the checked-in experiment and is emitted UNCHANGED — that
row is the direct H200 vs MI355X comparison, and a re-serialized copy that
differs in any byte is a different experiment.

Model repo ids marked VERIFY were not confirmed against HF; check them before
fan-out (`huggingface-cli repo info <id>`), fix MODELS, regenerate.
"""

from __future__ import annotations

from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent.parent
OUT_DIR = HERE / "experiments" / "mi355x"
CHECKED_IN_QWEN = HERE / "experiments" / "experiments.yaml"

# (file stem, model id, needs VERIFY, extra vllm args, nodes budgeted)
MODELS = [
    ("kimi-k25", "moonshotai/Kimi-K2.5", False,
     ["--tool-call-parser", "kimi_k2", "--enable-auto-tool-choice", "--reasoning-parser", "kimi_k2"], 4),
    ("kimi-k3", "moonshotai/Kimi-K3", True,
     ["--tool-call-parser", "kimi_k2", "--enable-auto-tool-choice", "--reasoning-parser", "kimi_k2"], 2),
    ("kimi-k27", "moonshotai/Kimi-K2.7", True,
     ["--tool-call-parser", "kimi_k2", "--enable-auto-tool-choice", "--reasoning-parser", "kimi_k2"], 2),
    ("deepseek-v4-flash", "deepseek-ai/DeepSeek-V4-Flash", True, [], 2),
    ("deepseek-v4-pro", "deepseek-ai/DeepSeek-V4-Pro", True, [], 2),
    ("glm-52", "zai-org/GLM-5.2", True, [], 2),
]

HEADER = """\
# GENERATED by scripts/gen_mi355x_manifests.py — edit that, not this.
# MI355X shard: {stem} ({nodes} node(s) budgeted, single node, TP=8).
# Power-cap arm: run the `powercap` variant only after
#   amd-smi set --power-cap <watts>     (record the value; restore after)
# No --pmc anywhere: counters serialize kernels (offline Tier-2 only).
"""

VERIFY_NOTE = """\
# VERIFY-MODEL-ID: {model} was not confirmed against HF before generation.
# Check it (and the guidellm backend model= below) before launching.
"""


def base_entry(stem: str, model: str, extra_vllm: list[str]) -> dict:
    return {
        "name": f"{stem}-tp8",
        "model": model,
        "prompt": "unused - guidellm_command supplies synthetic data",
        "tp": 8,
        "env": {"VLLM_ROCM_USE_AITER": "1"},
        "vllm_args": [
            "--trust-remote-code",
            "--tensor-parallel-size", "8",
            "--gpu-memory-utilization", "0.92",
            "--max-num-batched-tokens", "8192",
            "--max-num-seqs", "256",
            *extra_vllm,
        ],
        # The checked-in sweep shape (same as the Qwen row): 16 concurrent
        # streams, 16384/1024 ISL/OSL synthetic, 300s, over-saturation guard.
        # Identical across arms — the load shape is the one thing a sweep
        # cannot vary and still measure anything.
        "guidellm_command": [
            "run",
            "--backend",
            f"kind=openai_http,target=http://localhost:8000/v1,model={model},max_tokens=1024",
            "--profile", "kind=concurrent,streams=16,warmup=0.1,cooldown=0.1",
            "--constraint", "kind=max_duration,seconds=300",
            "--constraint", "kind=over_saturation",
            "--data", "kind=synthetic_text,prompt_tokens=16384,output_tokens=1024",
            "--output", f"kind=json,path=/workspace/{stem}-tp8.json",
        ],
        "variants": standard_variants(),
    }


def standard_variants() -> list[dict]:
    return [
        {"name": "base", "metadata": {"arm": "tuned"}},
        {"name": "rccl-log", "env": {"RCCL_DEBUG": "INFO"},
         "metadata": {"arm": "tuned+rccl-log",
                      "note": "algo/proto choice lands in the telemetry dir's server.log"}},
        {"name": "bad-tiny-batch",
         "vllm_args": ["--max-num-batched-tokens", "1024", "--max-num-seqs", "16"],
         "metadata": {"arm": "bad", "broken_knob": "batching starved"}},
        {"name": "bad-no-graphs", "vllm_args": ["--enforce-eager"],
         "metadata": {"arm": "bad", "broken_knob": "eager execution / launch gaps"}},
        {"name": "bad-kv-squeeze",
         "vllm_args": ["--gpu-memory-utilization", "0.60"],
         "metadata": {"arm": "bad", "broken_knob": "KV squeezed; preemption pressure"}},
        {"name": "powercap",
         "metadata": {"arm": "powercap",
                      "note": "identical config to base; host power cap lowered first. "
                              "Sampler records cap+energy, so tokens/joule is measured."}},
    ]


def k25_extra_variants() -> list[dict]:
    return [
        # RCCL Inspector env spelling varies with the RCCL the image ships;
        # both known spellings are set (unknown vars are ignored). Verify the
        # dump directory fills on first run; if not, check `strings librccl.so
        # | grep -i inspector` for this build's variable names.
        {"name": "rccl-inspector",
         "env": {"RCCL_ENABLE_INSPECTOR": "1",
                 "RCCL_INSPECTOR_ENABLE": "1",
                 "RCCL_INSPECTOR_DUMP_DIR": "/workspace/rccl-inspector"},
         "metadata": {"arm": "tuned+rccl-inspector",
                      "note": "one K2.5 config only; not the whole matrix"}},
        # Does vLLM's layerwise tracing flag emit ROCTx on ROCm? One run
        # answers it: markers land in the rocprof marker CSV or they don't.
        # If they don't, drop this arm — kernel names + queue ids carry the
        # taxonomy.
        {"name": "roctx-check",
         "vllm_args": ["--enable-layerwise-nvtx-tracing"],
         "metadata": {"arm": "tuned+roctx-check",
                      "note": "if rocprof's marker CSV is empty, the flag does not "
                              "emit ROCTx on ROCm; skip layerwise tracing"}},
    ]


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    for stem, model, verify, extra_vllm, nodes in MODELS:
        entry = base_entry(stem, model, extra_vllm)
        if stem == "kimi-k25":
            entry["variants"] = entry["variants"] + k25_extra_variants()
        doc = {"gpu_counts": [8], "experiments": [entry]}
        text = HEADER.format(stem=stem, nodes=nodes)
        if verify:
            text += VERIFY_NOTE.format(model=model)
        text += yaml.safe_dump(doc, sort_keys=False, width=100)
        path = OUT_DIR / f"{stem}.yaml"
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path}")

    # Qwen: the checked-in experiment, verbatim copy.
    qwen_path = OUT_DIR / "qwen-36-35b.yaml"
    qwen_path.write_text(
        "# COPY of the checked-in experiments.yaml, UNCHANGED — the direct\n"
        "# H200 vs MI355X comparison row. Regenerated by gen_mi355x_manifests.py.\n"
        + CHECKED_IN_QWEN.read_text(encoding="utf-8"),
        encoding="utf-8",
    )
    print(f"wrote {qwen_path}")


if __name__ == "__main__":
    main()
